#!/usr/bin/env python3
"""Standard-library check that the multiplication tensor of A = F_2[x]/(f), deg f = 4,
has bilinear rank > 8 over F_2 (or report a rank-8 decomposition subspace).

Principle.  Write the tensor through its four slices S_0..S_3 (4x4 matrices of the bilinear
forms (a, b) -> coefficient of x^k in a*b).  A decomposition of rank r is the same as r
rank-one matrices whose span contains S = <S_0..S_3>.  Rank <= 8 therefore holds iff some
8-dimensional subspace W containing S is spanned by the rank-one matrices it contains;
then W = S + <F1, F2, F3, F4> for rank-one F_i whose images in V = F_2^16 / S are
independent.

Search.  F1 is taken from one representative per orbit of the symmetry group generated by
M -> L_u^T M L_v (u, v units of A; they preserve S and rank) and M -> M^T (A is
commutative).  F2 < F3 run over all rank-one matrices.  For each triple, every rank-one
matrix is classified by its image modulo Q3 = <img F1, img F2, img F3>: those with zero
image lie in W3 = S + <F1, F2, F3>; the others fall into buckets, one per 4-dimensional
Q4 containing Q3.  W = preimage of Q4 is spanned by rank-ones iff the rank-ones in W3 and in
the bucket span a space of dimension 8.

Matrices are 16-bit integers (bit 4*i + j is entry (i, j)).
Usage: check_q2.py [f]   (f as an integer bit mask, default 21 = x^4 + x^2 + 1)
"""
import sys
import time


def mul(a, b, f, n):
  r = 0
  for i in range(n):
    if b >> i & 1:
      r ^= a << i
  for d in range(2 * n - 2, n - 1, -1):
    if r >> d & 1:
      r ^= f << (d - n)
  return r


def rank(vecs):
  basis = {}
  for v in vecs:
    while v:
      h = v.bit_length() - 1
      if h in basis:
        v ^= basis[h]
      else:
        basis[h] = v
        break
  return len(basis)


def reducer(basis_vecs):
  """Return (pivot dict, reduce function) for the span of basis_vecs."""
  piv = {}
  for v in basis_vecs:
    for h, b in piv.items():
      if v >> h & 1:
        v ^= b
    if v:
      h = v.bit_length() - 1
      for k in list(piv):
        if piv[k] >> h & 1:
          piv[k] ^= v
      piv[h] = v

  def red(x):
    for h, b in piv.items():
      if x >> h & 1:
        x ^= b
    return x
  return piv, red


def main():
  f = int(sys.argv[1]) if len(sys.argv) > 1 else 21
  n = f.bit_length() - 1
  assert n == 4
  t0 = time.time()
  slices = [0] * n
  for i in range(n):
    for j in range(n):
      z = mul(1 << i, 1 << j, f, n)
      for k in range(n):
        if z >> k & 1:
          slices[k] |= 1 << (n * i + j)
  pivS, redS = reducer(slices)
  assert len(pivS) == n
  funcs = list(range(1, 1 << n))
  def r1(a, b):
    m = 0
    for i in range(n):
      if a >> i & 1:
        m |= b << (n * i)
    return m
  ones = [(a, b, r1(a, b)) for a in funcs for b in funcs]
  img = [redS(m) for (_, _, m) in ones]
  # functional a (bit i = value on x^i) composed with multiplication by unit u
  units = [u for u in range(1, 1 << n) if rank([mul(u, 1 << j, f, n) for j in range(n)]) == n]
  def act(a, u):
    w = 0
    for j in range(n):
      z = mul(u, 1 << j, f, n)
      if bin(a & z).count('1') & 1:
        w |= 1 << j
    return w
  cls = {}
  for a in funcs:
    if a in cls:
      continue
    c = len(set(cls.values()))
    stack = [a]
    cls[a] = c
    while stack:
      x = stack.pop()
      for u in units:
        y = act(x, u)
        if y not in cls:
          cls[y] = c
          stack.append(y)
  reps = {}
  for idx, (a, b, _) in enumerate(ones):
    key = tuple(sorted((cls[a], cls[b])))
    reps.setdefault(key, idx)
  print(f'f={f}: {len(units)} units, {len(set(cls.values()))} functional classes, '
        f'{len(reps)} F1 representatives, {len(ones)} rank-one matrices', flush=True)
  N = len(ones)
  triples = hits = 0
  for rep in reps.values():
    for i2 in range(N):
      if i2 == rep:
        continue
      piv2, red2 = reducer([img[rep], img[i2]])
      if len(piv2) < 2:
        continue
      r2 = [red2(v) for v in img]
      for i3 in range(i2 + 1, N):
        if i3 == rep or r2[i3] == 0:
          continue
        triples += 1
        w3 = r2[i3]
        h3 = w3.bit_length() - 1
        common, buckets = [], {}
        for s in range(N):
          v = r2[s]
          if v >> h3 & 1:
            v ^= w3
          if v == 0:
            common.append(ones[s][2])
          else:
            buckets.setdefault(v, []).append(ones[s][2])
        rc = rank(common)
        for members in buckets.values():
          if len(members) >= 8 - rc and rank(common + members) == 8:
            hits += 1
            print('HIT', ones[rep][2], ones[i2][2], ones[i3][2], flush=True)
            print(f'RESULT f={f}: rank <= 8 is POSSIBLE')
            return
    print(f'  representative {rep} done: triples so far {triples}, hits {hits}, '
          f'{time.time() - t0:.0f}s', flush=True)
  print(f'RESULT f={f}: rank <= 8 is {"POSSIBLE" if hits else "IMPOSSIBLE"} '
        f'(triples {triples}, hits {hits})')


if __name__ == '__main__':
  main()
