#!/usr/bin/env python3
"""Exhaustive rank test for the multiplication tensor of A = F_q[x]/(f), q prime, deg f = n.

Decides whether R_{F_q}(A) <= n + m for m in {3, 4} by the subspace criterion
(rank <= n+m iff some (n+m)-dimensional W containing the slice span S is spanned by
rank-one matrices; W = S + <F1, ..., Fm>).  F1 runs over one representative per orbit of
the symmetry group generated by M -> L_u^T M L_v (u, v units) and M -> M^T; the middle
F's run over all rank-ones; the last one is handled by bucketing all rank-ones by their
projective image modulo the span of the previous images.

On the first hit it extracts an explicit decomposition, verifies it against the tensor and
writes it as JSON.  Without a hit the search is exhaustive and proves R > n + m.
Usage: rankq.py q m c0 c1 ... cn [--out file.json] [--all]
"""
import json
import sys
import time


def parse():
  argv = sys.argv[1:]
  out = None
  if '--out' in argv:
    k = argv.index('--out')
    out = argv[k + 1]
    argv = argv[:k] + argv[k + 2:]
  q, m = int(argv[0]), int(argv[1])
  f = [int(c) % q for c in argv[2:]]
  return q, m, f, out


def main():
  q, m, f, out = parse()
  n = len(f) - 1
  assert f[n] == 1
  inv = {a: pow(a, q - 2, q) for a in range(1, q)}

  def mul(x, y):
    t = [0] * (2 * n - 1)
    for i in range(n):
      for j in range(n):
        t[i + j] = (t[i + j] + x[i] * y[j]) % q
    for d in range(2 * n - 2, n - 1, -1):
      c = t[d]
      if c:
        for k in range(n + 1):
          t[d - n + k] = (t[d - n + k] - c * f[k]) % q
    return t[:n]

  def e(i):
    return [1 if k == i else 0 for k in range(n)]

  def echelon(vecs):
    """Reduced echelon basis as list of (pivot, vector) with pivot entry 1."""
    basis = []
    for v in vecs:
      v = list(v)
      for p, b in basis:
        if v[p]:
          c = v[p]
          v = [(x - c * y) % q for x, y in zip(v, b)]
      piv = next((k for k, x in enumerate(v) if x), None)
      if piv is None:
        continue
      s = inv[v[piv]]
      v = [x * s % q for x in v]
      nb = []
      for p, b in basis:
        if b[piv]:
          c = b[piv]
          b = [(x - c * y) % q for x, y in zip(b, v)]
        nb.append((p, b))
      basis = nb + [(piv, v)]
    return basis

  def reduce(v, basis):
    v = list(v)
    for p, b in basis:
      if v[p]:
        c = v[p]
        v = [(x - c * y) % q for x, y in zip(v, b)]
    return v

  def normalize(v):
    piv = next((k for k, x in enumerate(v) if x), None)
    if piv is None:
      return None
    s = inv[v[piv]]
    return tuple(x * s % q for x in v)

  nn = n * n
  slices = [[0] * nn for _ in range(n)]
  for i in range(n):
    for j in range(n):
      z = mul(e(i), e(j))
      for k in range(n):
        slices[k][i * n + j] = z[k]
  Sb = echelon(slices)
  assert len(Sb) == n
  funcs = []
  for code in range(1, q ** n):
    v = [(code // q ** i) % q for i in range(n)]
    if v[next(k for k, x in enumerate(v) if x)] == 1:
      funcs.append(tuple(v))
  fidx = {v: i for i, v in enumerate(funcs)}
  ones = []
  for a in funcs:
    for b in funcs:
      ones.append((a, b, [a[i] * b[j] % q for i in range(n) for j in range(n)]))
  img = [reduce(M, Sb) for (_, _, M) in ones]
  units = []
  for code in range(1, q ** n):
    u = [(code // q ** i) % q for i in range(n)]
    if len(echelon([mul(u, e(j)) for j in range(n)])) == n:
      units.append(u)
  cls = {}
  for a in funcs:
    if a in cls:
      continue
    c = len(set(cls.values()))
    cls[a] = c
    stack = [a]
    while stack:
      x = stack.pop()
      for u in units:
        w = normalize([sum(x[i] * mul(u, e(j))[i] for i in range(n)) % q for j in range(n)])
        if w not in cls:
          cls[w] = c
          stack.append(w)
  reps = {}
  for idx, (a, b, _) in enumerate(ones):
    reps.setdefault(tuple(sorted((cls[a], cls[b]))), idx)
  N = len(ones)
  print(f'q={q} f={f} n={n} target rank {n + m}: {len(units)} units, '
        f'{len(set(cls.values()))} functional classes, {len(reps)} F1 reps, {N} rank-ones', flush=True)
  t0 = time.time()
  count = 0

  def try_prefix(prefix):
    """prefix: indices of F1..F_{m-1}; bucket the last one.  Returns W rank-one list or None."""
    nonlocal count
    E = echelon([img[i] for i in prefix])
    if len(E) < len(prefix):
      return None
    count += 1
    common, buckets = [], {}
    for s in range(N):
      v = normalize(reduce(img[s], E))
      if v is None:
        common.append(s)
      else:
        buckets.setdefault(v, []).append(s)
    rc = len(echelon([ones[s][2] for s in common]))
    for members in buckets.values():
      if len(members) >= n + m - rc:
        if len(echelon([ones[s][2] for s in common + members])) == n + m:
          return common + members
    return None

  found = None
  for rep in reps.values():
    if m == 3:
      for i2 in range(N):
        if i2 != rep:
          found = try_prefix([rep, i2])
          if found:
            break
    else:
      for i2 in range(N):
        if i2 == rep:
          continue
        for i3 in range(i2 + 1, N):
          if i3 != rep:
            found = try_prefix([rep, i2, i3])
            if found:
              break
        if found:
          break
    if found:
      break
    print(f'  rep {rep} exhausted ({count} prefixes, {time.time() - t0:.0f}s)', flush=True)
  if not found:
    print(f'RESULT q={q} f={f}: rank <= {n + m} IMPOSSIBLE (exhaustive, {count} prefixes)')
    return
  # extract a basis of W from the rank-ones found, then express the slices
  basis_idx, E = [], []
  for s in found:
    if len(echelon([ones[t][2] for t in basis_idx + [s]])) > len(basis_idx):
      basis_idx.append(s)
  assert len(basis_idx) == n + m
  # solve slices[k] = sum_t c[t][k] * M_t by Gaussian elimination on the augmented system
  R = n + m
  cols = [ones[t][2] for t in basis_idx]
  C = [[0] * n for _ in range(R)]
  for k in range(n):
    # augmented matrix rows = coordinates (nn), columns = R unknowns + rhs
    A = [[cols[t][r] for t in range(R)] + [slices[k][r]] for r in range(nn)]
    row, pivs = 0, []
    for c in range(R):
      p = next((r for r in range(row, nn) if A[r][c]), None)
      if p is None:
        continue
      A[row], A[p] = A[p], A[row]
      s = inv[A[row][c]]
      A[row] = [x * s % q for x in A[row]]
      for r in range(nn):
        if r != row and A[r][c]:
          cc = A[r][c]
          A[r] = [(x - cc * y) % q for x, y in zip(A[r], A[row])]
      pivs.append(c)
      row += 1
    assert all(A[r][R] == 0 for r in range(row, nn)), 'slice not in span'
    for r, c in enumerate(pivs):
      C[c][k] = A[r][R]
  terms = [(list(ones[t][0]), list(ones[t][1]), C[i]) for i, t in enumerate(basis_idx)]
  # verify: sum_t a_t(i) b_t(j) c_t(k) == coefficient of x^k in x^i x^j
  for i in range(n):
    for j in range(n):
      z = mul(e(i), e(j))
      for k in range(n):
        acc = sum(a[i] * b[j] * c[k] for a, b, c in terms) % q
        assert acc == z[k], (i, j, k)
  print(f'RESULT q={q} f={f}: rank <= {n + m} POSSIBLE; verified decomposition with {R} terms')
  for a, b, c in terms:
    print('  a', a, 'b', b, 'c', c)
  if out:
    with open(out, 'w') as fh:
      json.dump({'q': q, 'modulus_low_to_high': f, 'rank': R,
                 'terms': [{'a': a, 'b': b, 'c': c} for a, b, c in terms],
                 'convention': 'x^i * x^j = sum_t a_t[i] b_t[j] sum_k c_t[k] x^k (mod f, mod q)'},
                fh, indent=1)


if __name__ == '__main__':
  main()
