"""Independent second encoding (shares no code with ../qlib.py, ../shapes.py, ../h3sat.py).

Trees: unrooted binary trees as edge lists; leaves 0..n-1.
- 5-leaf consistency patterns are obtained by brute force: generate all labelled 5-leaf trees by stepwise
  insertion and record their quartet vectors (no hand derivation).
- T1 shapes: generated by stepwise insertion of a new leaf into every edge of every shape on n-1 leaves,
  deduplicated by an AHU-style canonical code (different algorithm from ../shapes.py).
- Encoding: for trees T2..Tk, 3 indicator variables per quartet with exactly-one, and for every 5-set every
  non-tree pattern is forbidden by a direct clause (no auxiliary variables).
Usage: indep_cnf.py n k out_prefix   -> writes out_prefix_<i>.cnf for every T1 shape i, prints count.
"""
import sys, itertools
from collections import deque

def insert_leaf(edges, e, leaf, newnode):
    u, v = e
    out = [x for x in edges if x != e]
    out += [(u, newnode), (newnode, v), (newnode, leaf)]
    return out

def all_labelled_trees(n):
    # leaves 0..n-1, internal nodes labelled from 100 upwards
    trees = [[(0, 100), (1, 100), (2, 100)]]
    for leaf in range(3, n):
        nxt = []
        for t in trees:
            for e in t:
                nxt.append(insert_leaf(t, e, leaf, 100 + leaf - 2))
        trees = nxt
    return trees

def adjacency(edges):
    adj = {}
    for u, v in edges:
        adj.setdefault(u, []).append(v); adj.setdefault(v, []).append(u)
    return adj

def leaf_dists(edges, leaves):
    adj = adjacency(edges); D = {}
    for s in leaves:
        dist = {s: 0}; dq = deque([s])
        while dq:
            x = dq.popleft()
            for y in adj[x]:
                if y not in dist:
                    dist[y] = dist[x] + 1; dq.append(y)
        D[s] = dist
    return D

def quartet_vector(edges, n):
    D = leaf_dists(edges, range(n))
    vec = []
    for a, b, c, d in itertools.combinations(range(n), 4):
        sums = (D[a][b] + D[c][d], D[a][c] + D[b][d], D[a][d] + D[b][c])
        m = min(sums); assert sums.count(m) == 1
        vec.append(sums.index(m))
    return vec

def canon(edges):
    adj = adjacency(edges)
    nodes = list(adj)
    # centre by iterated leaf stripping
    deg = {x: len(adj[x]) for x in nodes}; alive = set(nodes)
    frontier = [x for x in nodes if deg[x] == 1]
    while len(alive) > 2:
        nf = []
        for x in frontier:
            alive.remove(x)
            for y in adj[x]:
                if y in alive:
                    deg[y] -= 1
                    if deg[y] == 1: nf.append(y)
        frontier = nf
    def code(x, parent):
        return '[' + ''.join(sorted(code(y, x) for y in adj[x] if y != parent)) + ']'
    c = sorted(alive)
    if len(c) == 1: return 'v' + code(c[0], None)
    return 'e' + '|'.join(sorted([code(c[0], c[1]), code(c[1], c[0])]))

def shapes_by_insertion(n):
    reps = {canon([(0, 100), (1, 100), (2, 100)]): [(0, 100), (1, 100), (2, 100)]}
    for leaf in range(3, n):
        nxt = {}
        for t in reps.values():
            for e in t:
                t2 = insert_leaf(t, e, leaf, 100 + leaf - 2)
                k = canon(t2)
                if k not in nxt: nxt[k] = t2
        reps = nxt
    return list(reps.values())

def main():
    n, k, prefix = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
    five = {tuple(quartet_vector(t, 5)) for t in all_labelled_trees(5)}
    assert len(five) == 15
    bad = [p for p in itertools.product(range(3), repeat=5) if p not in five]
    quarts = list(itertools.combinations(range(n), 4)); qpos = {q: i for i, q in enumerate(quarts)}
    shapes = shapes_by_insertion(n)
    nq = len(quarts)
    var = lambda t, q, s: 1 + (t * nq + q) * 3 + s   # t = 0..k-2 for trees T2..Tk
    nvars = (k - 1) * nq * 3
    base = []
    for t in range(k - 1):
        for q in range(nq):
            a, b, c = var(t, q, 0), var(t, q, 1), var(t, q, 2)
            base += [(a, b, c), (-a, -b), (-a, -c), (-b, -c)]
        for S in itertools.combinations(range(n), 5):
            # the 5 quartets of S in lexicographic order of 4-subsets (matches quartet_vector on 5 leaves)
            qi = [qpos[tuple(S[j] for j in sub)] for sub in itertools.combinations(range(5), 4)]
            for p in bad:
                base.append(tuple(-var(t, qi[j], p[j]) for j in range(5)))
    for si, t1 in enumerate(shapes):
        v1 = quartet_vector(t1, n)
        cls = base + [tuple(-var(t, q, v1[q]) for t in range(k - 1)) for q in range(nq)]
        with open(f'{prefix}_{si:03d}.cnf', 'w') as f:
            f.write(f'p cnf {nvars} {len(cls)}\n')
            for c in cls: f.write(' '.join(map(str, c)) + ' 0\n')
    print(len(shapes))

if __name__ == '__main__':
    main()
